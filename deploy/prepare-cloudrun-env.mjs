/**
 * Reads ../.env and writes cloudrun-env.generated.yaml for `gcloud run deploy --env-vars-file`.
 * Run: node deploy/prepare-cloudrun-env.mjs
 */
import fs from "fs";
import path from "path";
import { fileURLToPath } from "url";

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const root = path.resolve(__dirname, "..");
const envPath = path.join(root, ".env");
const outPath = path.join(__dirname, "cloudrun-env.generated.yaml");

const KEYS = [
  "DATABASE_URL",
  "DIRECT_URL",
  "GEMINI_API_KEY",
  "GEMINI_MODEL",
  "THEMEALDB_API_KEY",
  "OPENROUTER_API_KEY",
  "OPENROUTER_MODEL",
  "OPENROUTER_SITE_URL",
  "OPENROUTER_APP_NAME",
];

function parseDotEnv(text) {
  const env = {};
  for (const line of text.split(/\r?\n/)) {
    const t = line.trim();
    if (!t || t.startsWith("#")) continue;
    const eq = t.indexOf("=");
    if (eq <= 0) continue;
    const k = t.slice(0, eq).trim();
    let v = t.slice(eq + 1).trim();
    if (
      (v.startsWith('"') && v.endsWith('"')) ||
      (v.startsWith("'") && v.endsWith("'"))
    ) {
      v = v.slice(1, -1);
    }
    env[k] = v;
  }
  return env;
}

/** gcloud --env-vars-file requires every value to be a string (YAML `1` becomes int). */
function yamlString(s) {
  return JSON.stringify(String(s));
}

const raw = fs.readFileSync(envPath, "utf8");
const parsed = parseDotEnv(raw);
const lines = ["# Generated by deploy/prepare-cloudrun-env.mjs — do not commit", ""];
for (const k of KEYS) {
  if (parsed[k] !== undefined && parsed[k] !== "") {
    lines.push(`${k}: ${yamlString(parsed[k])}`);
  }
}
lines.push(`HOST: ${yamlString("0.0.0.0")}`);
fs.writeFileSync(outPath, lines.join("\n") + "\n", "utf8");
console.log("Wrote", outPath);
